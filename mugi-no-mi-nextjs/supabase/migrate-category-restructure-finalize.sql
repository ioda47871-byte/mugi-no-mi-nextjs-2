-- ----------------------------------------------------------------------------
-- STEP 6: 最終フォールバック
-- ----------------------------------------------------------------------------
-- preview.sql の自動判定で振り分けられなかった残りの 'bread' 行を、
-- 安全側のデフォルトとして「食パン」に割り当てます。
--
-- preview.sql のSTEP 5で確認した一覧の中に、実際には「食事パン」であるべき
-- 商品が含まれていた場合は、この STEP 6 実行後に、管理画面(/admin)の
-- 編集フォームから該当商品のカテゴリーを「食事パン」に手動で変更してください。

update public.products
set category_id = 'shokupan'
where category_id = 'bread';


-- ----------------------------------------------------------------------------
-- STEP 7: 移行後の確認クエリ
-- ----------------------------------------------------------------------------

-- 7-1. カテゴリーごとの件数を確認し、想定通りか目視で確認してください
select category_id, count(*) as product_count
from public.products
group by category_id
order by category_id;

-- 7-2. 旧カテゴリーID('bread'/'pastry'/'gift'/'kashi'/'shokuji')が
--      1件も残っていないことを確認してください(0行が返れば移行完了です)
select category_id, count(*) as remaining_old_rows
from public.products
where category_id in ('bread', 'pastry', 'gift', 'kashi', 'shokuji')
group by category_id;

-- ============================================================================
-- 上記 7-2 が0行であれば、カテゴリー再編は完了です。
