-- ----------------------------------------------------------------------------
-- 1. is_featured_home 列を追加する
-- ----------------------------------------------------------------------------
-- トップページの「おすすめ商品セクション」に表示する商品を管理者が個別に
-- 選べるようにするための列です。既定はfalse(表示しない)で、初期状態では
-- おすすめ商品セクションは空(コンポーネント側で0件時は非表示)になります。

alter table public.products
  add column if not exists is_featured_home boolean not null default false;


