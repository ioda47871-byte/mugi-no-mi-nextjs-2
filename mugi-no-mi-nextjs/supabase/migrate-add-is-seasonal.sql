-- ----------------------------------------------------------------------------
-- 1. is_seasonal 列を追加する
-- ----------------------------------------------------------------------------
-- 「季節限定」を tag列(text)の値で代用する設計は、tagが単一選択のため
-- 他のタグ(定番・人気・数量限定など)と共存できず実運用で問題が出るため、
-- 専用の boolean 列として独立させます。

alter table public.products
  add column if not exists is_seasonal boolean not null default false;


-- ----------------------------------------------------------------------------
-- 2. 既存データの移行
-- ----------------------------------------------------------------------------
-- これまで tag = '季節限定' として登録されていた商品を、
-- is_seasonal = true に反映します(データの意味を引き継ぐだけで、tag列は変更しません)。

update public.products
set is_seasonal = true
where tag = '季節限定';


-- ----------------------------------------------------------------------------
-- 3. tag列を自動でnullにするかどうか(提案・要判断)
-- ----------------------------------------------------------------------------
-- 上記2.の実行後、tag='季節限定' の行は is_seasonal=true と tag='季節限定' の
-- 両方が同時に立っている状態になります。これをそのままにするか、
-- tagをクリアするかは、実運用への影響を考慮して判断が必要なため、
-- このSQLでは自動実行せず提案のみとします。
--
-- 【提案】このSQL側では tag を自動で null にしないことを推奨します。理由:
--   a) 移行直後に公開サイト側のコードが両方(tagベースの旧表示・is_seasonalベースの
--      新表示)を見に行っても、表示が消えたり壊れたりするリスクがない
--      (今回のアプリ側の実装では、季節限定バッジは is_seasonal のみを見るように
--      変更済みなので、tag='季節限定' が残っていても二重表示にはなりません。
--      詳しくは本メッセージの「変更ファイル一覧」を参照してください)
--   b) 過去のデータ(いつ・どの商品が季節限定だったか)を tag列からも
--      振り返れる形で残せる
--   c) 誤って一括更新した場合に、tag列の値からis_seasonalの復元・検証がしやすい
--
-- 【選択肢A: 何もしない(推奨)】
--   このまま何も実行しない。tag='季節限定'の行は、今後は管理画面の編集フォームで
--   手動的に別のタグ('定番'/'人気'/'数量限定'/'なし')に更新していく運用とする。
--   (今回のアプリ側変更で、季節限定は編集フォームの「タグ」選択肢からは
--    削除しているため、新規に tag='季節限定' が設定されることはありません)
--
-- 【選択肢B: 移行対象だけをnullにする(実行する場合のみ、以下のコメントを外して実行)】
--   is_seasonal へ移行した行に限り、tagをクリアしたい場合:
--
--   -- update public.products
--   -- set tag = null
--   -- where tag = '季節限定';
--
--   ※ 選択肢Bを実行すると、その商品の「タグ表示」は空になり、
--     季節限定バッジ(is_seasonal由来)のみが表示される状態になります。
--     見た目上の変化はほぼありませんが、tag履歴は失われます。


