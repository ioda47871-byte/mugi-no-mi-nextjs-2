-- カテゴリーIDと日本語表示名の対応(アプリ全体でこのIDに統一しています):
--   shokupan   = 食パン
--   savory     = 惣菜パン
--   sweet      = 菓子パン
--   meal-bread = 食事パン
--
-- 「季節限定」はカテゴリーではなく、既存の is_seasonal 列で管理します
-- (このSQLでは触れません)。
