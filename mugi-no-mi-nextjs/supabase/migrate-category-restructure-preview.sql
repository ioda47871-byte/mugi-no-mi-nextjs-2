-- ----------------------------------------------------------------------------
-- STEP 0: 以前の版のマイグレーションを一部実行済みの場合の救済(安全のため)
-- ----------------------------------------------------------------------------
-- 旧版のSQLで 'kashi' / 'shokuji' という中間IDに変更済みの行があれば、
-- 正式なID('sweet' / 'meal-bread')に統一します。未実行なら何も起こりません。

update public.products set category_id = 'sweet'      where category_id = 'kashi';
update public.products set category_id = 'meal-bread' where category_id = 'shokuji';


-- ----------------------------------------------------------------------------
-- STEP 1: 旧 'pastry'(ペストリー)は全件「食事パン」へ
-- ----------------------------------------------------------------------------
-- クロワッサン等は「食事パンに統一する」という方針のため、判定不要で一括変更します。

update public.products
set category_id = 'meal-bread'
where category_id = 'pastry';


-- ----------------------------------------------------------------------------
-- STEP 2: 旧 'gift'(ギフト・季節限定)は全件「菓子パン」へ
-- ----------------------------------------------------------------------------

update public.products
set category_id = 'sweet'
where category_id = 'gift';


-- ----------------------------------------------------------------------------
-- STEP 3: 旧 'savory'(惣菜パン)はそのまま(IDのみ据え置き、変更不要)
-- ----------------------------------------------------------------------------
-- category_id = 'savory' の行は変更不要です(表示名も「惣菜パン」のまま)。
-- 実行するSQLはありません。


-- ----------------------------------------------------------------------------
-- STEP 4: 旧 'bread' を商品名から自動振り分け(判定できる分のみ)
-- ----------------------------------------------------------------------------
-- 'bread' は元々「食パン」「食事パン」の両方を含んでいたカテゴリーのため、
-- 商品名に含まれるキーワードから可能な範囲で自動判定します。
-- ここでは判定できる行だけを移行し、判定できない行は 'bread' のまま残します
-- (次のSTEP 5で一覧表示して確認できるようにするためです)。
--
-- 判定ルール(上から優先):
--   1. 商品名に「バゲット」「カンパーニュ」「ミッシュ」「ライ麦」を含む → meal-bread(食事パン)
--   2. 商品名に「食パン」「ブレッド」を含む → shokupan(食パン)
--   3. どちらにも一致しない行は、この時点では変更しません

-- 4-1. 食事パン判定(先に判定することで、優先ルールを保証)
update public.products
set category_id = 'meal-bread'
where category_id = 'bread'
  and (
    name ilike '%バゲット%' or
    name ilike '%カンパーニュ%' or
    name ilike '%ミッシュ%' or
    name ilike '%ライ麦%'
  );

-- 4-2. 食パン判定(4-1で既に移動した行は category_id <> 'bread' になっているため対象外)
update public.products
set category_id = 'shokupan'
where category_id = 'bread'
  and (
    name ilike '%食パン%' or
    name ilike '%ブレッド%'
  );


-- ----------------------------------------------------------------------------
-- STEP 5: 自動判定できなかった商品の確認(★この結果を必ず確認してください)
-- ----------------------------------------------------------------------------
-- 上記のキーワードに一致せず、category_id が 'bread' のまま残っている商品です。
-- ここに表示された商品は、次に実行する finalize.sql によって
-- 「食パン」に一括で割り当てられます。
--
-- 実際には「食事パン」であるべき商品が含まれている場合は、
-- finalize.sql を実行した"後"に、管理画面(/admin)の編集フォームから
-- 該当商品のカテゴリーを手動で「食事パン」に変更してください
-- (finalize.sql を実行する前に、この一覧をメモ・スクリーンショット等で
--  控えておくと後の手動修正がスムーズです)。

select id, name, price, category_id
from public.products
where category_id = 'bread'
order by name;

